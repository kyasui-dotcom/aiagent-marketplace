  function deliveryFollowupTaskForChannel(channel = '', fallback = 'research') {
    const normalized = String(channel || '').trim();
    if (normalized === 'x') return 'x_post';
    if (normalized === 'instagram') return 'instagram';
    if (normalized === 'reddit') return 'reddit';
    if (normalized === 'indie_hackers') return 'indie_hackers';
    if (normalized === 'email') return 'email_ops';
    if (normalized === 'github') return 'code';
    return String(fallback || 'research').trim() || 'research';
  }

