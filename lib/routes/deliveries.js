const GITHUB_EXECUTOR_MARKER = 'Generated by AIagent2 executor';
const PRODUCT_SHORT_NAME = 'CAIt';

function normalizeGithubExecutorPath(value = '') {
  const normalized = String(value || '').trim().replace(/\\/g, '/').replace(/^\/+/, '').replace(/\/{2,}/g, '/');
  if (!normalized || normalized.endsWith('/')) return '';
  if (normalized.includes('..') || normalized.startsWith('.')) return '';
  return normalized.slice(0, 180);
}

function sanitizeGithubExecutorSlug(value = '', fallback = 'delivery') {
  const slug = String(value || '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return (slug || fallback).slice(0, 48);
}

function githubExecutorPlanFromRequest(body = {}, repoMeta = {}) {
  const kind = sanitizeGithubExecutorSlug(body.kind || body.executor_kind || 'delivery');
  const rawTitle = String(body.title || body.source_delivery_title || kind).trim();
  const sourceJobId = String(body.source_job_id || body.job_id || body.jobId || '').trim();
  const titleSlug = sanitizeGithubExecutorSlug(rawTitle, kind);
  const shortJobId = sanitizeGithubExecutorSlug(sourceJobId, 'job').slice(0, 12);
  const branchName = `cait/${sanitizeGithubExecutorSlug(kind, 'executor')}-${titleSlug}-${shortJobId}`.slice(0, 120);
  const requestedPath = normalizeGithubExecutorPath(body.repo_path || '');
  const fallbackName = `${titleSlug || kind}-${shortJobId || 'delivery'}.md`;
  const filePath = requestedPath || `cait-deliveries/${fallbackName}`;
  const content = String(body.content || '').trim();
  const fileContent = [
    `${GITHUB_EXECUTOR_MARKER}`,
    `Generated by ${PRODUCT_SHORT_NAME} executor for \`${repoMeta.full_name || `${body.owner}/${body.repo}`}\`.`,
    '',
    content
  ].join('\n');
  const prTitle = String(body.pr_title || body.prTitle || `Add ${PRODUCT_SHORT_NAME} ${kind} handoff: ${rawTitle || kind}`).trim().slice(0, 180);
  const prBody = [
    `This PR was prepared from a ${PRODUCT_SHORT_NAME} delivery action.`,
    '',
    `- Source job: ${sourceJobId || 'not provided'}`,
    `- Executor kind: ${kind}`,
    `- File: \`${filePath}\``,
    '',
    'Review the generated file before merging.'
  ].join('\n');
  return { kind, branchName, filePath, fileContent, prTitle, prBody };
}

